"""The macro catalogue is generated, and these keep it from becoming a second source of truth.

MACROS.md lists every value the pipeline exports with its current value, so it is only useful while it matches the
macro files. It is written by step 11, which runs at the end of every pipeline execution, so the normal way to refresh
it is to run the pipeline. These tests fail when it drifts from the files, which also catches the case the catalogue
was built for: a macro file regenerated on its own, by `--only 19` or a partial re-run, while the rest stayed behind.

macro_notes.csv is the one hand-written part, where a macro worth citing is proposed without editing the generated
file. A note that names a macro which no longer exists would quietly disappear from the catalogue, so it is checked
too.
"""
import csv
import importlib.util
import os
import re
import sys

import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATALOGUE = os.path.join(ROOT, "MACROS.md")
NOTES = os.path.join(ROOT, "macro_notes.csv")
LATEX_DIR = os.path.join(ROOT, "latex")


@pytest.fixture(scope="module")
def checker():
    """Step 11 loaded as a module; its name starts with a digit, so it cannot be imported by name."""
    sys.path.insert(0, os.path.join(ROOT, "scripts"))
    spec = importlib.util.spec_from_file_location("step11", os.path.join(ROOT, "scripts", "11_check_manuscript.py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def exported_macros():
    out = {}
    for name in os.listdir(LATEX_DIR):
        if name.endswith("_variables.tex"):
            with open(os.path.join(LATEX_DIR, name), encoding="utf-8") as fh:
                out.update(re.findall(r"\\newcommand\{\\(\w+)\}\{([^}]*)\}", fh.read()))
    return out


def test_the_catalogue_on_disk_is_the_one_the_pipeline_would_write(checker):
    assert os.path.isfile(CATALOGUE), "MACROS.md is missing; run `python run_pipeline.py --only 11`"
    with open(CATALOGUE, encoding="utf-8") as fh:
        on_disk = fh.read()
    assert on_disk == checker.catalogue_markdown(), \
        "MACROS.md is out of date with latex/; run `python run_pipeline.py --only 11` to refresh it"


def test_the_catalogue_lists_every_exported_macro(checker):
    listed = set(re.findall(r"^\| `\\(\w+)` \|", checker.catalogue_markdown(), re.M))
    missing = sorted(set(exported_macros()) - listed)
    assert not missing, f"{len(missing)} exported macro(s) are absent from the catalogue, e.g. {missing[:5]}"


def test_the_catalogue_says_it_is_generated(checker):
    assert "Auto-generated by 11_check_manuscript.py" in checker.catalogue_markdown()


@pytest.mark.skipif(not os.path.isfile(NOTES), reason="no notes have been written yet")
def test_every_note_names_a_macro_that_exists():
    exported = exported_macros()
    with open(NOTES, encoding="utf-8", newline="") as fh:
        rows = [row for row in csv.DictReader(fh) if row.get("macro")]
    assert rows, "macro_notes.csv has a header but no rows; delete it rather than keeping it empty"
    unknown = sorted(row["macro"].strip() for row in rows if row["macro"].strip() not in exported)
    assert not unknown, f"{unknown} are proposed in macro_notes.csv but no step exports them"
    empty = [row["macro"] for row in rows if not row.get("note", "").strip()]
    assert not empty, f"{empty} have no note, which is the only thing the row is for"
