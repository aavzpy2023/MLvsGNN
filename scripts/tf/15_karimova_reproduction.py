"""
Step 15 (TensorFlow environment): reproduction of the deep-network results of Karimova & Senanayake (2025).

15a runs the original notebooks unchanged (nb3 baseline, nb7 importance groups, nb8 augmentation) in a temporary copy
of the original repository and compares the R2 they print with the values stored in the published notebooks.
15b re-runs the same protocol with the re-implementation in karimova_dnn.py over several seeds, so that the published
single-run values can be placed inside the run-to-run distribution of their own protocol. Only CSV files are written.
"""
import json
import multiprocessing as mp
import os
import re
import shutil
import sys
import tempfile
import time
from concurrent.futures import ThreadPoolExecutor

import numpy as np
import pandas as pd

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.append(os.path.dirname(os.path.abspath(__file__)))
from paths_config import RESULTS_DIR, LOGS_DIR
from logger_utils import setup_logger, explain

VERBATIM_CSV = os.path.join(RESULTS_DIR, "15_karimova_verbatim.csv")
RUNS_CSV = os.path.join(RESULTS_DIR, "15_karimova_reproduction.csv")
SUMMARY_CSV = os.path.join(RESULTS_DIR, "15_karimova_reproduction_summary.csv")

N_SEEDS = int(os.environ.get("MLGNN_K15_SEEDS", "10"))
RUN_VERBATIM = os.environ.get("MLGNN_K15_VERBATIM", "1") == "1"
THREADS_PER_WORKER = int(os.environ.get("MLGNN_TF_THREADS", "4"))
KERNEL_NAME = os.environ.get("MLGNN_K15_KERNEL", "myenv_paper")

# Notebook of each stage and the position of its 'Average' row among the R2 tables the notebook prints
VERBATIM_STAGES = [
    ("baseline", "3-DNN_Baseline/V2-3-Model_TgDHFR_2d-3d-fp-pic50_qt-pic50.ipynb", 0),
    ("sel_G1234", "7-Feature_Importance_byGroups/V2-7-1-Feature_Importance_byGroups.ipynb", 0),
    ("sel_G123", "7-Feature_Importance_byGroups/V2-7-1-Feature_Importance_byGroups.ipynb", 1),
    ("aug_G123", "8-Trainingset_Augmentation/V2-Model_TgDHFR_2d-3d-fp-pic50_qt-pic50-Augmented_Final_15.ipynb", -1),
]
PAPER_R2 = {"baseline": 0.75, "sel_G1234": 0.82, "sel_G123": None, "aug_G123": 0.85}
AVERAGE_ROW = re.compile(r"Average\s+(-?\d+\.\d+)\s+(-?\d+\.\d+)")


def average_rows(nb):
    """(R2, MAE) of every 'Average' row printed by a notebook, in cell order."""
    rows = []
    for cell in nb["cells"]:
        for out in cell.get("outputs", []):
            text = "".join(out.get("text", [])) + "".join(out.get("data", {}).get("text/plain", []))
            rows += [(float(r2), float(mae)) for r2, mae in AVERAGE_ROW.findall(text)]
    return rows


def execute_notebook(path, cwd):
    import nbformat
    from nbclient import NotebookClient
    nb = nbformat.read(path, as_version=4)
    NotebookClient(nb, kernel_name=KERNEL_NAME, timeout=None, resources={"metadata": {"path": cwd}}).execute()
    return nb


def run_verbatim(kd):
    """Runs nb3, nb7 and nb8 unchanged. The notebooks read their inputs from the working directory with partly flat and
    partly nested paths, so the copy gets the two shared tables at its root as well. nb7 and nb8 use the published
    importance table, so that only the network training differs from the published run."""
    work = tempfile.mkdtemp(prefix="karimova_verbatim_")
    try:
        shutil.copytree(kd.KARIMOVA_DIR, work, dirs_exist_ok=True, ignore=shutil.ignore_patterns(".git"))
        for src in (kd.KARIMOVA_TABLE, kd.KARIMOVA_IMPORTANCE):
            shutil.copy(src, work)
        # nb3 rewrites the descriptor table at the root: it runs in its own copy so that nb7/nb8 read the published one
        work_nb3 = os.path.join(work, "_nb3")
        shutil.copytree(work, work_nb3, ignore=shutil.ignore_patterns("_nb3"))
        notebooks = sorted({nb for _, nb, _ in VERBATIM_STAGES})
        cwd_of = {nb: (work_nb3 if nb.startswith("3-") else work) for nb in notebooks}
        env_threads = str(THREADS_PER_WORKER)
        os.environ.update(TF_NUM_INTRAOP_THREADS=env_threads, TF_NUM_INTEROP_THREADS="1", OMP_NUM_THREADS=env_threads)
        with ThreadPoolExecutor(max_workers=len(notebooks)) as pool:
            futures = {nb: pool.submit(execute_notebook, os.path.join(cwd_of[nb], nb), cwd_of[nb]) for nb in notebooks}
            executed = {}
            for nb, fut in futures.items():
                executed[nb] = fut.result()
                print(f"  [15a] executed {nb}")
        regenerated = os.path.join(work_nb3, "V2-merged_df_noOutliers.csv")
        if os.path.exists(regenerated):
            a, b = pd.read_csv(regenerated), pd.read_csv(kd.KARIMOVA_TABLE)
            same = a.shape == b.shape and np.allclose(a.select_dtypes("number").to_numpy(), b.select_dtypes("number").to_numpy(),
                                                       equal_nan=True)
            print(f"  [15a] descriptor table regenerated by nb3 identical to the published one: {same}")
    finally:
        shutil.rmtree(work, ignore_errors=True)

    rows = []
    for stage, nb, pos in VERBATIM_STAGES:
        with open(os.path.join(kd.KARIMOVA_DIR, nb), encoding="utf-8") as fh:
            printed = average_rows(json.load(fh))
        rerun = average_rows(executed[nb])
        rows.append(dict(stage=stage, notebook=nb, r2_printed=printed[pos][0], mae_printed=printed[pos][1],
                         r2_rerun=rerun[pos][0], mae_rerun=rerun[pos][1], r2_paper=PAPER_R2[stage]))
    return pd.DataFrame(rows)


def _ensemble_scores(kd, Xtr, ytr, Xte, yte, seed):
    return kd.scores(yte, kd.ensemble_predict(Xtr, ytr, Xte, yte, Xte, seed))


def run_seed(seed):
    """Full original protocol for one seed: baseline, fresh importance, group selection (published and fresh
    importances) and nb8 augmentation. Every evaluation uses the original 15% test set, which is also the monitoring set."""
    import karimova_dnn as kd
    df, features = kd.load_table()
    y = df["pIC50 Value"]
    tr_idx, te_idx = kd.split_indices(len(df))
    ytr, yte = y.iloc[tr_idx], y.iloc[te_idx]
    out = []

    def prepared(columns):
        pre = kd.Preprocessor().fit(df.iloc[tr_idx][columns])
        return pre.transform(df.iloc[tr_idx][columns]), pre.transform(df.iloc[te_idx][columns])

    Xtr, Xte = prepared(features)
    r2, mae = _ensemble_scores(kd, Xtr, ytr, Xte, yte, seed)
    out.append(dict(seed=seed, stage="baseline", pi_source="-", n_features=Xtr.shape[1], r2=r2, mae=mae))

    # nb5: one network, early-stopped on the test set, importance by permutation on the test set
    pi_model = kd.train_dnn(Xtr, ytr, Xte, yte, seed * 100 + 50)
    sources = {"published": kd.published_importance(),
               "fresh": (kd.permutation_importance_mean(pi_model, Xte, yte), list(Xte.columns))}

    for source, (imp, names) in sources.items():
        for stage, groups in (("sel_G1234", ("G1", "G2", "G3", "G4")), ("sel_G123", ("G1", "G2", "G3"))):
            cols = kd.select_groups(imp, names, groups)
            Xtr_g, Xte_g = prepared(cols)
            r2, mae = _ensemble_scores(kd, Xtr_g, ytr, Xte_g, yte, seed)
            out.append(dict(seed=seed, stage=stage, pi_source=source, n_features=Xtr_g.shape[1], r2=r2, mae=mae))

        y_val, pred, _ = kd.nb8_protocol(Xtr_g, ytr, Xte_g, yte, seed)
        r2, mae = kd.scores(y_val, pred)
        out.append(dict(seed=seed, stage="aug_G123", pi_source=source, n_features=Xtr_g.shape[1], r2=r2, mae=mae))
    print(f"  [15b] seed {seed} done: " + " | ".join(f"{o['stage']}/{o['pi_source']} R2={o['r2']:.3f}" for o in out),
          flush=True)
    return out


def _init_worker(threads):
    os.environ["MLGNN_TF_THREADS"] = str(threads)


def main():
    setup_logger(os.path.join(LOGS_DIR, "15_karimova_reproduction.log"))
    print("=" * 105)
    print("15_karimova_reproduction.py — Reproduction of the original deep-network results (TensorFlow environment)")
    print("=" * 105)
    explain("What this step does", """
        The original study reports R2 = 0.75 for its baseline network, 0.82 after keeping the descriptors with a positive
        permutation importance, and 0.85 after adding Gaussian-noise copies of the training molecules. Each value comes from one
        execution of a notebook on one train/test split. Part 15a runs those notebooks again, unchanged, and compares the
        printed R2 with the published notebooks. Part 15b re-runs the same protocol, step by step, with several random seeds,
        to see how much these values move from one execution to the next. Both parts use the original protocol, including the
        choices that the next step (16) examines as possible information leaks.
    """)
    import karimova_dnn as kd
    commit = kd.check_clone()
    print(f"  Original repository: {kd.KARIMOVA_DIR} (commit {commit})")
    os.makedirs(RESULTS_DIR, exist_ok=True)

    if RUN_VERBATIM:
        t0 = time.time()
        verbatim = run_verbatim(kd)
        verbatim.to_csv(VERBATIM_CSV, index=False)
        print(verbatim.round(4).to_string(index=False))
        print(f"  [15a] {time.time() - t0:.0f}s -> {VERBATIM_CSV}")

    t0 = time.time()
    n_workers = max(1, min(N_SEEDS, (os.cpu_count() or 1) // THREADS_PER_WORKER))
    print(f"\n  [15b] {N_SEEDS} seeds on {n_workers} workers x {THREADS_PER_WORKER} threads")
    with mp.get_context("spawn").Pool(n_workers, initializer=_init_worker, initargs=(THREADS_PER_WORKER,)) as pool:
        runs = pd.DataFrame([row for rows in pool.map(run_seed, range(1, N_SEEDS + 1)) for row in rows])
    runs.to_csv(RUNS_CSV, index=False)

    summary = (runs.groupby(["stage", "pi_source"], sort=False)
               .agg(n_seeds=("r2", "size"), n_features=("n_features", "median"), r2_mean=("r2", "mean"),
                    r2_sd=("r2", "std"), r2_min=("r2", "min"), r2_max=("r2", "max"), mae_mean=("mae", "mean"))
               .reset_index())
    summary["r2_paper"] = summary["stage"].map(PAPER_R2)
    summary.to_csv(SUMMARY_CSV, index=False)
    print(summary.round(4).to_string(index=False))
    print(f"  [15b] {time.time() - t0:.0f}s -> {RUNS_CSV}, {SUMMARY_CSV}")


if __name__ == "__main__":
    main()
