"""Exports the configuration of this run as LaTeX macros, so that the manuscript never states one by hand.

The results macros come from the steps that measure them, and `paths_config.py` holds the settings those steps read.
Nothing exported the settings themselves, so the manuscript spelled out a tree count, a training schedule, a grid and
a seed as literals, and a sentence describing them kept reading correctly after the setting behind it changed. These
are cheap to recompute -- no model is fitted here -- which is why they are not written by the expensive steps that use
them: `latex/paper_variables.tex` belongs to step 01, and regenerating it would mean running the nested
cross-validation again.

Values that live inside one step rather than in the configuration (the outlier fence factor of step 00, the clipping
margin of step 01) are read from its source with `ast`, without importing it, so that loading this exporter never runs
another step's module-level code.
"""
import ast
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from paths_config import CFG, LATEX_DIR, NOISE_LEVELS, RANDOM_STATE, TEST_SIZE
from qsartools.featurization import morgan_fingerprints
from qsartools.latex import format_macros

LATEX_CONFIG = os.path.join(LATEX_DIR, "config_variables.tex")


def assigned_literal(script, name):
    """The value assigned to `name` at the top level of `script`, read from its source without importing it.

    Args:
        script: file name of a script under scripts/.
        name: the variable to read.
    """
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), script)
    with open(path, encoding="utf-8") as fh:
        tree = ast.parse(fh.read(), filename=script)
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", None) == name for t in node.targets):
            return ast.literal_eval(node.value)
    raise KeyError(f"{name} is not assigned at the top level of {script}")


def default_of(function, parameter):
    """Default value of `parameter` in `function`, so that a documented default is quoted and not copied."""
    import inspect
    return inspect.signature(function).parameters[parameter].default


def config_values():
    """Every configuration value the manuscript states, keyed by the macro that carries it."""
    import gnn_utils

    sizes, depths, dropouts = gnn_utils.HIDDEN_SIZES, gnn_utils.DEPTHS, gnn_utils.DROPOUTS
    default = gnn_utils.DEFAULT_CONFIG
    return {
        "RandomSeed": RANDOM_STATE,
        # Two macros rather than the list that step 04 exports, because the sentence names them one by one
        "NoiseLevelHigh": max(NOISE_LEVELS),
        "NoiseLevelLow": min(NOISE_LEVELS),
        "NTrees": CFG["N_ESTIMATORS_TREES"],
        "HoldoutPct": f"{TEST_SIZE * 100:.0f}",
        "IqrFactor": assigned_literal("00_prepare_dataset.py", "IQR_FACTOR"),
        "ClipMargin": f"{assigned_literal('01_nested_cv_stacking.py', 'CLIP_MARGIN'):.0f}",
        "MorganRadius": default_of(morgan_fingerprints, "radius"),
        "GnnEpochs": gnn_utils.EPOCHS,
        "GnnHiddenSize": default["d_h"],
        "GnnDepth": default["depth"],
        # Written as a word, because the sentences that state it read "no dropout" rather than a number
        "GnnDropoutWord": "no dropout" if default["dropout"] == 0 else f"dropout {default['dropout']}",
        "GnnGridHiddenSizes": " or ".join(str(s) for s in sizes),
        "GnnGridDepths": " or ".join(str(d) for d in depths),
        "GnnGridDropouts": " or ".join(f"{p:g}" for p in dropouts),
        "GnnInnerValPct": f"{gnn_utils.INNER_VALIDATION_FRACTION * 100:.0f}",
        "GnnInnerTrainPct": f"{100 - gnn_utils.INNER_VALIDATION_FRACTION * 100:.0f}",
        "DmpnnEnsembleSeeds": assigned_literal("19_gnn_strong_baselines.py", "N_ENSEMBLE"),
    }


def main():
    values = config_values()
    os.makedirs(os.path.dirname(LATEX_CONFIG), exist_ok=True)
    with open(LATEX_CONFIG, "w", encoding="utf-8") as fh:
        fh.write(format_macros(values, header="Auto-generated by 00.1_export_config.py; the settings this run used, "
                                              "so that no sentence states one by hand"))
    print(f"[EXPORT] {len(values)} configuration variables saved to {LATEX_CONFIG}")
    for name, value in values.items():
        print(f"  {name:<22} {value}")


if __name__ == "__main__":
    main()
